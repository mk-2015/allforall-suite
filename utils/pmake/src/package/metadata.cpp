#include <package/metadata.hpp>
#include <sstream>

namespace pmake::package {

std::string generate_metadata(const config::ProjectConfig& config)
{
    std::ostringstream oss;
    oss << "# Generated by PMAKE\n";
    oss << "pkgname = " << config.package.name << "\n";
    oss << "pkgver = " << config.package.version << "-" << config.package.release << "\n";
    oss << "pkgdesc = " << config.package.description << "\n";
    oss << "arch = " << config.package.architecture << "\n";
    oss << "license = ";
    for (size_t i = 0; i < config.package.license.size(); ++i) {
        oss << config.package.license[i];
        if (i + 1 < config.package.license.size()) oss << " ";
    }
    oss << "\n";
    return oss.str();
}

} // namespace pmake::package

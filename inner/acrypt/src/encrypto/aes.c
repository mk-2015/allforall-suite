static const acry_u8 RCON[15] = { 0x00u, 0x01u, 0x02u, 0x04u, 0x08u, 0x10u, 0x20u, 0x40u, 0x80u, 0x1bu, 0x36u, 0x6cu, 0xd8u, 0xabu, 0x4du };

static acry_u8 gmul(acry_u8 a, acry_u8 b) {
    acry_u8 p = 0;
    for (int i = 0; i < 8; i++) {
        if (b & 1) p ^= a;
        acry_u8 hi = (acry_u8)(a & 0x80u);
        a = (acry_u8)(a << 1);
        if (hi) a = (acry_u8)(a ^ 0x1Bu);
        b >>= 1;
    }
    return p;
}

/* state[16] uses column-major indexing per FIPS-197: byte (row r, col c) is
 * at state[r + 4*c], matching the input byte order directly. */

static void sub_bytes(acry_u8 state[16]) {
    for (int i = 0; i < 16; i++) state[i] = SBOX[state[i]];
}

static void inv_sub_bytes(acry_u8 state[16]) {
    for (int i = 0; i < 16; i++) state[i] = INV_SBOX[state[i]];
}

static void shift_rows(acry_u8 state[16]) {
    acry_u8 tmp[16];
    for (int r = 0; r < 4; r++) {
        for (int c = 0; c < 4; c++) {
            tmp[r + 4 * c] = state[r + 4 * ((c + r) % 4)];
        }
    }
    memcpy(state, tmp, 16);
}

static void inv_shift_rows(acry_u8 state[16]) {
    acry_u8 tmp[16];
    for (int r = 0; r < 4; r++) {
        for (int c = 0; c < 4; c++) {
            tmp[r + 4 * c] = state[r + 4 * ((c - r + 4) % 4)];
        }
    }
    memcpy(state, tmp, 16);
}

static void mix_columns(acry_u8 state[16]) {
    for (int c = 0; c < 4; c++) {
        acry_u8 s0 = state[0 + 4 * c];
        acry_u8 s1 = state[1 + 4 * c];
        acry_u8 s2 = state[2 + 4 * c];
        acry_u8 s3 = state[3 + 4 * c];

        state[0 + 4 * c] = (acry_u8)(gmul(s0, 2) ^ gmul(s1, 3) ^ s2 ^ s3);
        state[1 + 4 * c] = (acry_u8)(s0 ^ gmul(s1, 2) ^ gmul(s2, 3) ^ s3);
        state[2 + 4 * c] = (acry_u8)(s0 ^ s1 ^ gmul(s2, 2) ^ gmul(s3, 3));
        state[3 + 4 * c] = (acry_u8)(gmul(s0, 3) ^ s1 ^ s2 ^ gmul(s3, 2));
    }
}

static void inv_mix_columns(acry_u8 state[16]) {
    for (int c = 0; c < 4; c++) {
        acry_u8 s0 = state[0 + 4 * c];
        acry_u8 s1 = state[1 + 4 * c];
        acry_u8 s2 = state[2 + 4 * c];
        acry_u8 s3 = state[3 + 4 * c];

        state[0 + 4 * c] = (acry_u8)(gmul(s0, 14) ^ gmul(s1, 11) ^ gmul(s2, 13) ^ gmul(s3, 9));
        state[1 + 4 * c] = (acry_u8)(gmul(s0, 9) ^ gmul(s1, 14) ^ gmul(s2, 11) ^ gmul(s3, 13));
        state[2 + 4 * c] = (acry_u8)(gmul(s0, 13) ^ gmul(s1, 9) ^ gmul(s2, 14) ^ gmul(s3, 11));
        state[3 + 4 * c] = (acry_u8)(gmul(s0, 11) ^ gmul(s1, 13) ^ gmul(s2, 9) ^ gmul(s3, 14));
    }
}

static void add_round_key(acry_u8 state[16], const acry_u32 *round_keys, int round) {
    for (int c = 0; c < 4; c++) {
        acry_u32 word = round_keys[round * 4 + c];
        state[0 + 4 * c] = (acry_u8)(state[0 + 4 * c] ^ (acry_u8)(word >> 24));
        state[1 + 4 * c] = (acry_u8)(state[1 + 4 * c] ^ (acry_u8)(word >> 16));
        state[2 + 4 * c] = (acry_u8)(state[2 + 4 * c] ^ (acry_u8)(word >> 8));
        state[3 + 4 * c] = (acry_u8)(state[3 + 4 * c] ^ (acry_u8)(word));
    }
}

static acry_u32 sub_word(acry_u32 w) {
    return ((acry_u32)SBOX[(w >> 24) & 0xFFu] << 24) |
           ((acry_u32)SBOX[(w >> 16) & 0xFFu] << 16) |
           ((acry_u32)SBOX[(w >> 8) & 0xFFu] << 8) |
           ((acry_u32)SBOX[w & 0xFFu]);
}

static acry_u32 rot_word(acry_u32 w) {
    return (w << 8) | (w >> 24);
}

static void key_expansion(AES_HANDLE *ctx, const acry_u8 *key, int Nk) {
    int Nr = ctx->num_rounds;
    acry_u32 *w = ctx->round_keys;
    int total_words = 4 * (Nr + 1);

    for (int i = 0; i < Nk; i++) {
        w[i] = ((acry_u32)key[4 * i] << 24) | ((acry_u32)key[4 * i + 1] << 16) |
               ((acry_u32)key[4 * i + 2] << 8) | ((acry_u32)key[4 * i + 3]);
    }

    for (int i = Nk; i < total_words; i++) {
        acry_u32 temp = w[i - 1];
        if (i % Nk == 0) {
            temp = sub_word(rot_word(temp)) ^ ((acry_u32)RCON[i / Nk] << 24);
        } else if (Nk > 6 && i % Nk == 4) {
            temp = sub_word(temp);
        }
        w[i] = w[i - Nk] ^ temp;
    }
}

AES_HANDLE AES_HANDLE_open(const acry_u8 *key, size_t key_len) {
    AES_HANDLE ctx;
    memset(&ctx, 0, sizeof(ctx));

    int Nk;
    switch (key_len) {
        case 16: Nk = 4;  ctx.num_rounds = 10; break;
        case 24: Nk = 6;  ctx.num_rounds = 12; break;
        case 32: Nk = 8;  ctx.num_rounds = 14; break;
        default:
            ctx.num_rounds = 0; /* invalid key length; caller must check */
            return ctx;
    }

    key_expansion(&ctx, key, Nk);
    return ctx;
}

int AES_HANDLE_close(AES_HANDLE ctx) {
    memset(&ctx, 0, sizeof(ctx));
    return 0;
}

void AES_encrypt_block(const AES_HANDLE *ctx, const acry_u8 in[AES_BLOCK_SIZE], acry_u8 out[AES_BLOCK_SIZE]) {
    acry_u8 state[16];
    memcpy(state, in, 16);
    int Nr = ctx->num_rounds;

    add_round_key(state, ctx->round_keys, 0);
    for (int round = 1; round < Nr; round++) {
        sub_bytes(state);
        shift_rows(state);
        mix_columns(state);
        add_round_key(state, ctx->round_keys, round);
    }
    sub_bytes(state);
    shift_rows(state);
    add_round_key(state, ctx->round_keys, Nr);

    memcpy(out, state, 16);
}

void AES_decrypt_block(const AES_HANDLE *ctx, const acry_u8 in[AES_BLOCK_SIZE], acry_u8 out[AES_BLOCK_SIZE]) {
    acry_u8 state[16];
    memcpy(state, in, 16);
    int Nr = ctx->num_rounds;

    add_round_key(state, ctx->round_keys, Nr);
    for (int round = Nr - 1; round >= 1; round--) {
        inv_shift_rows(state);
        inv_sub_bytes(state);
        add_round_key(state, ctx->round_keys, round);
        inv_mix_columns(state);
    }
    inv_shift_rows(state);
    inv_sub_bytes(state);
    add_round_key(state, ctx->round_keys, 0);

    memcpy(out, state, 16);
}